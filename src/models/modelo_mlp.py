import pandas as pd
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.metrics import roc_auc_score

print("1. A carregar os dados processados de treino e teste...")
df_treino = pd.read_csv('diabetes_treino_processado.csv')
df_teste = pd.read_csv('diabetes_teste_processado.csv')

# Separar características (X) e a variável alvo (y - Outcome)
X_treino = df_treino.drop('Outcome', axis=1)
y_treino = df_treino['Outcome']

X_teste = df_teste.drop('Outcome', axis=1)
y_teste = df_teste['Outcome']

print("2. A inicializar e treinar o modelo MLP (Rede Neural)...")
# hidden_layer_sizes=(16, 8) significa que criámos duas camadas ocultas:
# a primeira com 16 neurónios e a segunda com 8 neurónios.
# max_iter=500 dá espaço suficiente para a rede aprender com os dados.
modelo_mlp = MLPClassifier(
    hidden_layer_sizes=(16, 8),
    max_iter=500,
    random_state=42
)

# Treinar a rede neural estritamente com os dados de treino
modelo_mlp.fit(X_treino, y_treino)
print("3. Treinamento concluído com sucesso!\n")

# 4. Fazer previsões usando o conjunto de teste (os dados que a rede nunca viu)
previsoes = modelo_mlp.predict(X_teste)

# 5. Avaliação do Desempenho
acuracia = accuracy_score(y_teste, previsoes)
print("-" * 45)
print(f"Acurácia (Accuracy) do modelo MLP: {acuracia * 100:.2f}%")
print("-" * 45)

print("\nRelatório de Classificação Detalhado:")
print(classification_report(y_teste, previsoes))

print("Matriz de Confusão:")
print(confusion_matrix(y_teste, previsoes))


# O cálculo da AUC exige as probabilidades, não apenas a previsão final (0 ou 1)
probabilidades = modelo_mlp.predict_proba(X_teste)[:, 1]
auc = roc_auc_score(y_teste, probabilidades)

print(f"AUC do modelo MLP (none - base): {auc:.4f}")

import pandas as pd
import warnings
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score
from sklearn.model_selection import GridSearchCV
# O uso do Pipeline do imblearn é OBRIGATÓRIO para evitar vazamento de dados no SMOTE/ADASYN
from imblearn.pipeline import Pipeline
from imblearn.over_sampling import SMOTE, ADASYN
from sklearn.metrics import confusion_matrix

warnings.filterwarnings('ignore') # Ocultar os avisos de convergência para limpar o ecrã

print("1. A carregar os dados...")
df_treino = pd.read_csv('diabetes_treino_processado.csv')
df_teste = pd.read_csv('diabetes_teste_processado.csv')

X_treino = df_treino.drop('Outcome', axis=1)
y_treino = df_treino['Outcome']
X_teste = df_teste.drop('Outcome', axis=1)
y_teste = df_teste['Outcome']

# Função auxiliar para treinar e extrair as três métricas
def avaliar_modelo(modelo, X_tr, y_tr, X_te, y_te):
    modelo.fit(X_tr, y_tr)
    previsoes = modelo.predict(X_te)
    probabilidades = modelo.predict_proba(X_te)[:, 1]

    acc = accuracy_score(y_te, previsoes)
    f1 = f1_score(y_te, previsoes, average='weighted')
    auc = roc_auc_score(y_te, probabilidades)
    return acc, f1, auc

# Modelo base com 1000 iterações (para evitar o aviso de convergência)
mlp_base = MLPClassifier(max_iter=1000, random_state=42)

# Parâmetros para a fase "Ajustada" (GridSearch)
param_grid = {
    'mlp__hidden_layer_sizes': [(16, 8), (32, 16)],
    'mlp__activation': ['relu', 'tanh'],
    'mlp__alpha': [0.0001, 0.001]
}

resultados = {}

print("2. A iniciar os testes (isto pode demorar alguns minutos)...\n")

# --- CENÁRIO 1: NONE (Sem balanceamento) ---
print("-> A rodar Cenário: NONE...")
pipe_none = Pipeline([('mlp', mlp_base)])
# Base
acc_b, f1_b, auc_b = avaliar_modelo(pipe_none, X_treino, y_treino, X_teste, y_teste)
# Ajustado
grid_none = GridSearchCV(pipe_none, param_grid, cv=5, scoring='roc_auc', n_jobs=-1)
acc_a, f1_a, auc_a = avaliar_modelo(grid_none, X_treino, y_treino, X_teste, y_teste)
resultados['none'] = [acc_b, f1_b, auc_b, acc_a, f1_a, auc_a]

# --- CENÁRIO 2: SMOTE ---
print("-> A rodar Cenário: SMOTE...")
pipe_smote = Pipeline([('smote', SMOTE(random_state=42)), ('mlp', mlp_base)])
# Base
acc_b, f1_b, auc_b = avaliar_modelo(pipe_smote, X_treino, y_treino, X_teste, y_teste)
# Ajustado
grid_smote = GridSearchCV(pipe_smote, param_grid, cv=5, scoring='roc_auc', n_jobs=-1)
acc_a, f1_a, auc_a = avaliar_modelo(grid_smote, X_treino, y_treino, X_teste, y_teste)
resultados['SMOTE'] = [acc_b, f1_b, auc_b, acc_a, f1_a, auc_a]

# --- CENÁRIO 3: ADASYN ---
print("-> A rodar Cenário: ADASYN...")
pipe_adasyn = Pipeline([('adasyn', ADASYN(random_state=42)), ('mlp', mlp_base)])
# Base
acc_b, f1_b, auc_b = avaliar_modelo(pipe_adasyn, X_treino, y_treino, X_teste, y_teste)
# Ajustado
grid_adasyn = GridSearchCV(pipe_adasyn, param_grid, cv=5, scoring='roc_auc', n_jobs=-1)
acc_a, f1_a, auc_a = avaliar_modelo(grid_adasyn, X_treino, y_treino, X_teste, y_teste)
resultados['ADASYN'] = [acc_b, f1_b, auc_b, acc_a, f1_a, auc_a]

# --- IMPRIMIR TABELA FINAL PARA OS SLIDES ---
print("\n" + "="*85)
print(f"{'Cenário':<10} | {'Acc base':<10} | {'F1 base':<10} | {'AUC base':<10} | {'Acc ajust.':<10} | {'F1 ajust.':<10} | {'AUC ajust.':<10}")
print("-" * 85)
for cenario, mets in resultados.items():
    print(f"{cenario:<10} | {mets[0]:.4f}     | {mets[1]:.4f}    | {mets[2]:.4f}     | {mets[3]:.4f}     | {mets[4]:.4f}     | {mets[5]:.4f}")
print("="*85)


# Obter as previsões do melhor modelo (ADASYN Ajustado)
previsoes_campeas = grid_adasyn.predict(X_teste)

# Gerar a nova matriz
matriz_campea = confusion_matrix(y_teste, previsoes_campeas)

print("--- NOVA MATRIZ DE CONFUSÃO (ADASYN AJUSTADO) ---")
print(matriz_campea)

import pandas as pd
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import accuracy_score, roc_auc_score, recall_score, confusion_matrix, f1_score
from imblearn.pipeline import Pipeline
from imblearn.over_sampling import SMOTE, ADASYN
import warnings
warnings.filterwarnings('ignore') # Limpa avisos da tela para manter o output limpo

# 0. CARREGAR OS DADOS PROCESSADOS (Separados previamente em treino e teste)
df_treino = pd.read_csv('diabetes_treino_processado.csv')
df_teste = pd.read_csv('diabetes_teste_processado.csv')

X_treino = df_treino.drop('Outcome', axis=1)
y_treino = df_treino['Outcome']
X_teste = df_teste.drop('Outcome', axis=1)
y_teste = df_teste['Outcome']

# 1. CRIAR O MODELO BASE (Rede Neural MLP com 1000 épocas e semente fixa)
mlp = MLPClassifier(max_iter=1000, random_state=42)

# 2. DEFINIR OS CENÁRIOS COM PIPELINE
cenarios = {
    "NONE": Pipeline([('mlp', mlp)]),
    "SMOTE": Pipeline([('smote', SMOTE(random_state=42)), ('mlp', mlp)]),
    "ADASYN": Pipeline([('adasyn', ADASYN(random_state=42)), ('mlp', mlp)])
}

# 3. LOOP DE TREINAMENTO E AVALIAÇÃO DOS 3 CENÁRIOS
print("=== RESULTADOS DA REPLICAÇÃO (BASELINE MLP) ===")
for nome, pipeline in cenarios.items():
    pipeline.fit(X_treino, y_treino) # O modelo aprende com os dados de treino
    previsoes = pipeline.predict(X_teste) # O modelo faz as previsões no teste
    probabilidades = pipeline.predict_proba(X_teste)[:, 1] # Pega as probabilidades para a curva ROC

    # Calcula as métricas gerais
    acc = accuracy_score(y_teste, previsoes)
    auc = roc_auc_score(y_teste, probabilidades)
    f1 = f1_score(y_teste, previsoes)

    print(f"{nome:6} -> Acurácia: {acc:.4f} | F1: {f1:.4f} | AUC: {auc:.4f}")

    # Extrair Recall e Matriz de Confusão especificamente do cenário NONE
    if nome == "NONE":
        recall = recall_score(y_teste, previsoes)
        matriz = confusion_matrix(y_teste, previsoes)

# 4. EXIBIÇÃO DOS DETALHES DO CENÁRIO BASE
print("\n=== DETALHES DO CENÁRIO NONE ===")
print(f"Recall: {recall:.4f} ({(recall*100):.2f}%)")
print(f"Matriz de Confusão:\n{matriz}")

